export type TranslationKey = keyof typeof en;
export type Locale = "en" | "es";

const I18nContext = createContext<{
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: TranslationKey, params?: Record<string, string | number>) => string;
  labels: {
    channel: (ch: Channel) => string;
    role: (r: Role) => string;
    status: (s: RepStatus) => string;
    priority: (p: PriorityType) => string;
    stage: (st: string) => string;
  };
}>({
  locale: "en",
  setLocale: () => {},
  t: (k) => en[k] || k,
  labels: {
    channel: (c) => c,
    role: (r) => r,
    status: (s) => s,
    priority: (p) => p,
    stage: (st) => st,
  },
});

export function I18nProvider({
  children,
}: {
  children: React.ReactNode;
}): React.ReactElement {
  const [locale, setLocaleState] = useState<Locale>(() => {
    if (typeof window !== "undefined") {
      const saved = localStorage.getItem("ceg_crm_locale") as Locale | null;
      if (saved && (saved === "en" || saved === "es")) return saved;
    }
    return "en";
  });

  const setLocale = (l: Locale) => {
    setLocaleState(l);
    if (typeof window !== "undefined") {
      localStorage.setItem("ceg_crm_locale", l);
    }
  };

  const t = (
    key: TranslationKey,
    params?: Record<string, string | number>,
  ): string => {
    const dict = locale === "es" ? es : en;
    let str = dict[key] || en[key] || key;
    if (params) {
      Object.entries(params).forEach(([k, v]) => {
        str = str.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
      });
    }
    return str;
  };

  const labels = {
    channel: (ch: Channel) => {
      const map: Record<Channel, TranslationKey> = {
        call: "Voice",
        voicemail: "Voicemail",
        sms: "SMS",
        whatsapp: "WhatsApp",
        messenger: "Messenger",
        instagram: "Instagram",
        email: "Email",
        telegram: "Telegram",
        note: "ChannelNote",
      };
      return t(map[ch]);
    },
    role: (r: Role) => {
      const map: Record<Role, TranslationKey> = {
        owner: "OwnerRole",
        admin: "AdminRole",
        manager: "ManagerRole",
        senior_rep: "SeniorRepRole",
        rep: "RepRole",
        viewer: "ViewerRole",
      };
      return t(map[r] || "RepRole");
    },
    status: (s: RepStatus) => {
      const map: Record<RepStatus, TranslationKey> = {
        available: "StatusAvailable",
        busy: "StatusBusy",
        away: "StatusAway",
        offline: "StatusOffline",
      };
      return t(map[s] || "StatusOffline");
    },
    priority: (p: PriorityType) => {
      const map: Partial<Record<PriorityType, TranslationKey>> = {
        overdue_payment: "OverduePayment",
        high_priority: "HighPriority",
        missed_call: "MissedCall",
        overdue_task: "OverdueTask",
        unanswered: "UnansweredMessage",
        buying_interest: "BuyingInterest",
        new_lead: "NewLead",
      };
      return t(map[p] || "AllPriority");
    },
    stage: (st: string) => {
      const key = st.charAt(0).toUpperCase() + st.slice(1).toLowerCase();
      return (
        (locale === "es"
          ? es[key as TranslationKey]
          : en[key as TranslationKey]) || st
      );
    },
  };

  return React.createElement(
    I18nContext.Provider,
    { value: { locale, setLocale, t, labels } },
    children,
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
